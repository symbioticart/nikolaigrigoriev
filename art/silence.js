/* Единая модель тишины/«смерти» — один источник для всех поверхностей.
   Утверждено автором 2026-07-27: быстрое угасание со 2-го дня, авто-возврат при
   возврате данных, растворение в ПУСТОЙ (ivory) холст — не к чёрному.

   gap = число подряд идущих дней молчания (0 = день с данными / свежий). */
(function (root) {
  var SILENCE = {
    // Визуальные параметры увядания для рендера картины.
    params: function (gap) {
      var g = Math.max(0, gap - 1);            // старт на 2-й день молчания
      return {
        gray:   Math.min(1, g / 13),           // цвет уходит к ~14-му дню
        fade:   Math.min(1, g / 29),           // растворение в ivory-холст к ~30-му дню (смерть = пусто)
        margin: Math.min(1, g / 29),           // форма стягивается в шаге с растворением
      };
    },
    // Оттенок ячейки архива на той же кривой:
    //   день с данными = почти чёрный, тишина светлеет, смерть = почти белый (пустой холст).
    shade: function (gap) {
      var p = this.params(gap);
      var t = Math.max(p.gray * 0.5, p.fade);  // 0 (свежая тишина) → 1 (мертва)
      var L = 0.17 + (0.95 - 0.17) * t;         // тёмно-серый → почти белый
      var v = Math.round(Math.min(1, L) * 255);
      return 'rgb(' + v + ',' + v + ',' + v + ')';
    },
  };
  root.SILENCE = SILENCE;
  if (typeof module !== 'undefined' && module.exports) module.exports = SILENCE;
})(typeof window !== 'undefined' ? window : this);
